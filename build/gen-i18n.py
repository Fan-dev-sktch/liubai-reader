#!/usr/bin/env python3
"""Regenerate www/i18n-data.js: collect every tr() key and fixed string, add Traditional Chinese
(OpenCC character table + Taiwan wording rules), English and French from i18n/en_fr.py."""
import json, os, re, subprocess, sys, tempfile
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "i18n"))
from en_fr import T
from zh_tw import RULES, WHOLE
keys_file = os.path.join(tempfile.gettempdir(), "liubai-i18n-keys.json")
subprocess.run(["node", os.path.join(ROOT, "build", "i18n-keys.js"), os.path.join(ROOT, "www"), keys_file], check=True)
keys = [x["k"] for x in json.load(open(keys_file, encoding="utf-8"))]
src = open(os.path.join(ROOT, "www", "zhconv-data.js"), encoding="utf-8").read()
m = re.search(r'export const S2T = \["([^"]*)", "([^"]*)"\]', src)
S2T = dict(zip(m.group(1), m.group(2)))
def tw(s):
    if s in WHOLE: return WHOLE[s]
    out = "".join(S2T.get(c, c) for c in s)
    for a, b in RULES: out = out.replace(a, b)
    return out
SKIP = {"留"}
rows, missing = [], []
for k in keys:
    if k in SKIP: continue
    if k not in T: missing.append(k); continue
    en, fr = T[k]
    rows.append([k, tw(k), en, fr])
if missing:
    print("missing translations:", missing); sys.exit(1)
unused = [k for k in T if k not in keys]
if unused: print("unused translations:", unused)
with open(os.path.join(ROOT, "www", "i18n-data.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by build/gen-i18n.py — edit i18n/en_fr.py or i18n/zh_tw.py instead.\n")
    f.write("// [简体中文, 繁體中文, English, Français]\nexport const STRINGS = [\n")
    for r in rows: f.write(" " + json.dumps(r, ensure_ascii=False) + ",\n")
    f.write("];\n")
print("i18n rows", len(rows))
